def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    lines = [u'# -*- coding: utf-8 -*-',
             u'# 第 8 轮：解题篇界面文案补译（章节跳转按钮 / 音乐室 UI 与曲名）',
             u'# 由 work/scripts/zz_gen_ui_tl.py 生成',
             u'translate schinese strings:']
    for old, new in PAIRS:
        lines.append(u'    old "%s"' % esc(old))
        lines.append(u'    new "%s"' % esc(new))
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(u'\n'.join(lines) + u'\n')
    print("wrote", OUT, len(PAIRS), "pairs")


if __name__ == '__main__':
    main()
