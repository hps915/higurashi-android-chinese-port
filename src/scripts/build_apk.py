# -*- coding: utf-8 -*-
"""Rebuild a Ren'Py Android APK with replaced/added game files.

- Copies every original entry byte-for-byte (raw compressed data preserved),
  except entries whose APK path is in `replace` (rewritten, deflate) and
  old JAR-signature files (regenerated by the signer).
- Appends new entries from `add` (deflate).
- 4-byte aligns data offsets of STORED entries (zipalign-equivalent), so
  resources.arsc stays valid on modern Android.
- Rebuilds central directory, then signs with uber-apk-signer.

Usage:
  build_apk.py <src.apk> <out.apk> <game_dir> <include_prefixes csv>
where files under <game_dir> matching <include_prefixes> (rel paths) are
mapped to APK names by prefixing each path component with 'x-' under
assets/x-game/.
"""
import os
import struct
import subprocess
import sys
import zipfile

TOOLS = r"D:\Galgame\寒蝉鸣泣之时\安卓移植版1\tools"
SIGNER = os.path.join(TOOLS, "uber-apk-signer-1.3.0.jar")
KEYSTORE = os.path.join(TOOLS, "higurashi_cn.keystore")
KS_PASS = "higurashi2024"

LOCAL_SIG = 0x04034B50
CENTRAL_SIG = 0x02014B50
EOCD_SIG = 0x06054B50
SKIP_PREFIXES = ("META-INF/",)
# original APK entries to drop (superseded / dead weight)
SKIP_ENTRIES = {"assets/x-game/x-movie/x-mv01.mp4"}


def to_apk_name(game_rel):
    parts = ["assets", "x-game"] + [("x-" + p) for p in game_rel.replace("\\", "/").split("/")]
    return "/".join(parts)


# 绝对不能打进包里的目录/文件（测试残留、存档、备份、缓存）
EXCLUDE_DIRS = ("saves/", "cache/", "tl/None/")
EXCLUDE_SUFFIXES = (".bak", ".rpy", ".txt", ".log", ".rpyb")


def collect_game_files(game_dir, prefixes):
    out = {}
    for root, dirs, files in os.walk(game_dir):
        for f in files:
            full = os.path.join(root, f)
            rel = os.path.relpath(full, game_dir).replace("\\", "/")
            if f.endswith(".rpy"):
                continue  # ship compiled .rpyc only
            if rel.startswith(EXCLUDE_DIRS) or f.endswith(EXCLUDE_SUFFIXES):
                continue
            if any(rel == p or rel.startswith(p.rstrip("/") + "/") or rel.startswith(p) for p in prefixes):
                out[rel] = full
    return out


def read_local_header(f, offset):
    f.seek(offset)
    hdr = f.read(30)
    assert struct.unpack("<I", hdr[:4])[0] == LOCAL_SIG, "bad local header"
    (sig, ver, flags, method, mtime, mdate, crc, csize, usize,
     nlen, elen) = struct.unpack("<IHHHHHIIIHH", hdr)
    name = f.read(nlen)
    extra = f.read(elen)
    data_off = f.tell()
    return dict(flags=flags, method=method, mtime=mtime, mdate=mdate, crc=crc,
                csize=csize, usize=usize, name=name, extra=extra, data_off=data_off)


def write_local(f, name_bytes, method, mtime, mdate, crc, csize, usize, data, extra,
                align=4):
    """Write local header + data; returns data offset (pads `extra` for alignment
    when method==STORE)."""
    if method == zipfile.ZIP_STORED and align:
        base = f.tell() + 30 + len(name_bytes) + len(extra)
        pad = (align - (base % align)) % align
        extra = extra + b"\x00" * pad
    off = f.tell()
    header = struct.pack("<IHHHHHIIIHH", LOCAL_SIG, 20, 0, method, mtime, mdate,
                         crc, csize, usize, len(name_bytes), len(extra))
    f.write(header)
    f.write(name_bytes)
    f.write(extra)
    data_off = f.tell()
    f.write(data)
    return off, data_off


def rebuild(src, dst, game_files, extras=None):
    zin = zipfile.ZipFile(src)
    raw = open(src, "rb")
    entries = zin.infolist()

    replace_map = {}  # apk name -> local file (from game dir)
    for rel, full in game_files.items():
        replace_map[to_apk_name(rel)] = full
    for apk_path, local in (extras or {}).items():
        replace_map[apk_path] = local

    with open(dst, "wb") as f:
        central = []
        for e in entries:
            if any(e.filename.startswith(p) for p in SKIP_PREFIXES):
                continue
            if e.filename in SKIP_ENTRIES:
                continue
            if "META-INF" in e.filename:
                continue
            lh = read_local_header(raw, e.header_offset)
            raw.seek(lh["data_off"])
            data = raw.read(lh["csize"])
            if e.filename in replace_map:
                content = open(replace_map[e.filename], "rb").read()
                import zlib
                comp = zlib.compressobj(9, zlib.DEFLATED, -15)
                data = comp.compress(content) + comp.flush()
                method = zipfile.ZIP_DEFLATED
                crc = zlib.crc32(content) & 0xFFFFFFFF
                csize, usize = len(data), len(content)
                extra = b""
                mtime, mdate = lh["mtime"], lh["mdate"]
            else:
                method, crc, csize, usize = lh["method"], lh["crc"], lh["csize"], lh["usize"]
                extra = b""
                mtime, mdate = lh["mtime"], lh["mdate"]
            off, _ = write_local(f, lh["name"], method, mtime, mdate, crc,
                                 csize, usize, data, extra)
            central.append((e, lh["name"], off, method, crc, csize, usize, mtime, mdate))

        # new entries
        import zlib
        for rel, full in sorted(game_files.items()):
            apk_name = to_apk_name(rel).encode()
            if any(c[0] is not None and c[0].filename == apk_name.decode() for c in central):
                continue  # already replaced above
            content = open(full, "rb").read()
            crc = zlib.crc32(content) & 0xFFFFFFFF
            mtime, mdate = 0x68F3, 0x5A21  # 2024-06-24
            if rel.lower().endswith(".ogv"):
                # video must be STORED (uncompressed) for reliable Android seek/decode
                data = content
                off, _ = write_local(f, apk_name, zipfile.ZIP_STORED, mtime, mdate,
                                     crc, len(data), len(content), data, b"")
                central.append((None, apk_name, off, zipfile.ZIP_STORED, crc,
                                len(data), len(content), mtime, mdate))
            else:
                comp = zlib.compressobj(9, zlib.DEFLATED, -15)
                data = comp.compress(content) + comp.flush()
                off, _ = write_local(f, apk_name, zipfile.ZIP_DEFLATED, mtime, mdate,
                                     crc, len(data), len(content), data, b"")
                central.append((None, apk_name, off, zipfile.ZIP_DEFLATED, crc,
                                len(data), len(content), mtime, mdate))

        # central directory
        cd_start = f.tell()
        for orig, name, off, method, crc, csize, usize, mtime, mdate in central:
            ext_attr = orig.external_attr if orig else (0o644 << 16)
            hdr = struct.pack("<IHHHHHHIIIHHHHHII", CENTRAL_SIG,
                              (orig.create_system << 8) | 20 if orig else (3 << 8) | 20,
                              20, 0, method, mtime, mdate, crc, csize, usize,
                              len(name), 0, 0, 0, 0, ext_attr, off)
            f.write(hdr)
            f.write(name)
        cd_size = f.tell() - cd_start
        f.write(struct.pack("<IHHHHIIH", EOCD_SIG, 0, 0, len(central), len(central),
                            cd_size, cd_start, 0))
    raw.close()
    zin.close()
    print(f"rebuilt {dst}: {len(central)} entries")


def sign(apk):
    if not os.path.exists(KEYSTORE):
        subprocess.run(["keytool", "-genkeypair", "-keystore", KEYSTORE,
                        "-alias", "higurashi", "-keyalg", "RSA", "-keysize", "2048",
                        "-validity", "10950", "-storepass", KS_PASS, "-keypass", KS_PASS,
                        "-dname", "CN=Higurashi CN Port, O=Personal"],
                       check=True)
    # APK 超过 2GB 时 uber-apk-signer 内置的 zipalign 会失败（32 位索引限制）。
    # rebuild() 自己已经按 4 字节对齐了所有 STORED 条目，所以这里跳过 zipalign。
    args = ["java", "-jar", SIGNER, "-a", apk,
            "--ks", KEYSTORE, "--ksAlias", "higurashi",
            "--ksPass", KS_PASS, "--ksKeyPass", KS_PASS,
            "--overwrite"]
    size = os.path.getsize(apk)
    if size > (2 << 30):
        args.append("--skipZipAlign")
        print("APK 体积 %.2f GB > 2GB，跳过 signer 的 zipalign（rebuild 已自带 4 字节对齐）"
              % (size / float(1 << 30)))
    r = subprocess.run(args,
                       capture_output=True, text=True, encoding="gbk", errors="replace")
    print(r.stdout[-2000:] if r.stdout else "", r.stderr[-500:] if r.stderr else "")
    if r.returncode != 0:
        raise SystemExit(f"signing failed: {r.returncode}")


def verify_start_targets(game_dir, game_files):
    """安全检查：screens.rpy 里 Start('xxx') 的每个目标标签，必须在编译产物里存在。
    缺一个就会在安卓上闪退（Ren'Py 找不到 label 时直接杀掉进程）。
    注意：.rpy 不随包发出，所以标签名从 game_dir 直接扫源文件。"""
    import re

    def walk(ext):
        for root, _dirs, files in os.walk(game_dir):
            for f in files:
                if f.endswith(ext):
                    yield os.path.join(root, f)

    labels = set()
    for p in walk(".rpy"):
        try:
            src = open(p, encoding="utf-8", errors="replace").read()
        except Exception:
            continue
        for m in re.finditer(r"^\s*label\s+([A-Za-z_]\w*)", src, re.M):
            labels.add(m.group(1))

    starts = set()
    screens = os.path.join(game_dir, "screens.rpy")
    if os.path.exists(screens):
        src = open(screens, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r"Start\(['\"]([^'\"]+)['\"]\)", src):
            starts.add(m.group(1))

    missing = sorted(s for s in starts if s not in labels)
    zz = sorted(s for s in starts if s.startswith("zz_op_"))
    print("Start() targets:", len(starts), "zz_op:", zz)
    print("labels defined:", len(labels))
    if missing:
        raise SystemExit("BUILD ABORTED: Start() targets with no label: %s" % missing)
    print("Start() target check: OK")


def main():
    src, dst, game_dir = sys.argv[1], sys.argv[2], sys.argv[3]
    prefixes = sys.argv[4].split(",") if len(sys.argv) > 4 else []
    extras = {}
    if len(sys.argv) > 5 and sys.argv[5]:
        for pair in sys.argv[5].split(";"):
            k, v = pair.split("=", 1)
            extras[k] = v
    game_files = collect_game_files(game_dir, prefixes)
    print(f"{len(game_files)} game files to inject, {len(extras)} direct overrides")
    # 关键文件必须存在，否则章节入口会跳到不存在的标签导致闪退
    for must in ("zz_op.rpyc",):
        if must not in game_files:
            raise SystemExit("BUILD ABORTED: %s not found under %s (compile the project first)"
                             % (must, game_dir))
    verify_start_targets(game_dir, game_files)
    for rel in sorted(game_files):
        print("  ", to_apk_name(rel))
    for k in extras:
        print("  ", k, "(direct)")
    rebuild(src, dst, game_files, extras)
    sign(dst)
    # verify zip integrity
    z = zipfile.ZipFile(dst)
    bad = z.testzip()
    print("zip integrity:", "FAILED at " + bad if bad else "OK", f"({len(z.namelist())} entries)")
    # 打完之后再确认一次：zz_op.rpyc 真的在包里
    names = set(z.namelist())
    for must in ("assets/x-game/x-zz_op.rpyc",):
        print("post-check", must, "->", "OK" if must in names else "MISSING!")
        if must not in names:
            raise SystemExit("BUILD ABORTED: %s missing from final APK" % must)


if __name__ == "__main__":
    main()
